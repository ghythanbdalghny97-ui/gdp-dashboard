import streamlit as st
import pandas as pd

st.set_page_config(
    page_title="Medical Health Prediction Dashboard",
    page_icon="🩺",
)

st.title("🩺 لوحة التنبؤ بالمؤشرات الصحية والجلطات المتقدمة")
st.write("مرحباً بك في نظامك الطبي الذكي. يرجى إدخال بيانات المريض من القائمة الجانبية للحصول على التحليل الشامل والرسوم البيانية الفورية.")

# القائمة الجانبية لإدخال بيانات المريض
st.sidebar.header("بيانات المريض الحيوية")

def user_input_features():
    age = st.sidebar.slider("العمر", 10, 100, 35)
    bmi = st.sidebar.slider("مؤشر كتلة الجسم (BMI)", 10.0, 50.0, 24.5)
    bp = st.sidebar.slider("ضغط الدم (Systolic)", 80, 200, 125)
    glucose = st.sidebar.slider("مستوى السكر في الدم", 70, 300, 110)
    cholesterol = st.sidebar.slider("مستوى الكوليسترول", 120, 300, 200)
    
    data = {
        'العمر': age,
        'كتلة الجسم (BMI)': bmi,
        'ضغط الدم': bp,
        'السكر': glucose,
        'الكوليسترول': cholesterol
    }
    features = pd.DataFrame(data, index=[0])
    return features

df = user_input_features()

st.subheader("📊 ملخص المؤشرات المدخلة:")
st.dataframe(df)

# زر إجراء التحليل
if st.button("إجراء التحليل الشامل والتنبؤ"):
    # حساب معامل الخطورة التجريبي بناءً على المؤشرات الحيوية
    risk_score = (df['كتلة الجسم (BMI)'][0] * 0.3) + (df['ضغط الدم'][0] * 0.25) + (df['السكر'][0] * 0.2) + (df['الكوليسترول'][0] * 0.15) + (df['العمر'][0] * 0.1)
    
    st.subheader("نتائج التنبؤ والتحليل الطبي:")
    
    # عرض مؤشر مرئي للخطورة
    st.metric(label="مؤشر الخطر المحتمل", value=f"{risk_score:.1f}%")
    
    if risk_score > 65:
        st.error("⚠️ تحذير عالي المستوى: المؤشرات الحيوية تدل على احتمالية مرتفعة لوجود مخاطر صحية أو مؤشرات مبكرة للجلطات. يُنصح بمراجعة الطبيب المختص فوراً وإجراء الفوصات المخبرية اللازمة.")
    elif risk_score > 45:
        st.warning("⚠️ تنبيه متوسط: بعض المؤشرات مرتفعة قليلاً عن المعدل الطبيعي. يُفضل تنظيم الغذاء، ممارسة الرياضة، ومتابعة الفحص دورياً.")
    else:
        st.success("✅ المؤشرات مستقرة ضمن النطاق الطبيعي والأمور الصحية ممتازة ولا توجد مخاطر ظاهرة حالياً.")

    # إضافة رسم بياني توضيحي للمقارنة بالمعدلات الطبيعية
    st.subheader("📈 رسم بياني توضيحي للمؤشرات مقارنة بالحدود العامة:")
    chart_data = pd.DataFrame({
        'المؤشر': ['كتلة الجسم', 'ضغط الدم', 'السكر', 'الكوليسترول'],
        'القيمة الحالية': [df['كتلة الجسم (BMI)'][0], df['ضغط الدم'][0], df['السكر'][0], df['الكوليسترول'][0]],
        'الحد الأقصى الطبيعي الآمن': [25, 130, 140, 200]
    })
    st.bar_chart(chart_data.set_index('المؤشر'))



